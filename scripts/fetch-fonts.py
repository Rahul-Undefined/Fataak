"""
Downloads the bundled fonts (all SIL Open Font License) from Google Fonts as variable-weight latin woff2 files
into src/renderer/public/fonts and writes fonts.css next to them. Run once when the font list changes:
    python scripts/fetch-fonts.py
"""
from __future__ import annotations

import re
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'src' / 'renderer' / 'public' / 'fonts'
OUT.mkdir(parents=True, exist_ok=True)
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'

# family → (Google Fonts query, css family name)
FONTS = {
    'inter': ('Inter:wght@400..700', 'Inter'),
    'manrope': ('Manrope:wght@400..700', 'Manrope'),
    'outfit': ('Outfit:wght@400..700', 'Outfit'),
    'space-grotesk': ('Space+Grotesk:wght@400..700', 'Space Grotesk'),
    'plus-jakarta-sans': ('Plus+Jakarta+Sans:wght@400..700', 'Plus Jakarta Sans'),
    'sora': ('Sora:wght@400..700', 'Sora'),
    'dm-sans': ('DM+Sans:wght@400..700', 'DM Sans'),
    'jetbrains-mono': ('JetBrains+Mono:wght@400..700', 'JetBrains Mono'),
    'fira-code': ('Fira+Code:wght@400..700', 'Fira Code'),
    'ibm-plex-mono': ('IBM+Plex+Mono:wght@400;500;600', 'IBM Plex Mono'),
    'source-code-pro': ('Source+Code+Pro:wght@400..700', 'Source Code Pro'),
    'geist-mono': ('Geist+Mono:wght@400..700', 'Geist Mono'),
}

css_out = ['/* bundled fonts, SIL Open Font License; generated by scripts/fetch-fonts.py */']
for key, (query, family) in FONTS.items():
    req = urllib.request.Request(f'https://fonts.googleapis.com/css2?family={query}&display=swap', headers={'User-Agent': UA})
    css = urllib.request.urlopen(req, timeout=30).read().decode('utf-8')
    # keep only the latin block(s); each @font-face has a unicode-range and one woff2 url
    faces = re.findall(r'/\* (\w[\w-]*) \*/\s*@font-face\s*\{(.*?)\}', css, re.S)
    n = 0
    for subset, body in faces:
        if subset != 'latin':
            continue
        url = re.search(r'url\((https://[^)]+\.woff2)\)', body).group(1)
        weight = re.search(r'font-weight:\s*([^;]+);', body).group(1).strip()
        style = re.search(r'font-style:\s*([^;]+);', body)
        fname = f'{key}-{weight.replace(" ", "-")}.woff2'
        data = urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=60).read()
        (OUT / fname).write_bytes(data)
        css_out.append(f"@font-face {{ font-family: '{family}'; font-style: {style.group(1).strip() if style else 'normal'}; font-weight: {weight}; font-display: swap; src: url('./{fname}') format('woff2'); }}")
        n += 1
        print(f'{family:20} {weight:10} {len(data) // 1024:4} KB  {fname}')
    if not n:
        raise SystemExit(f'no latin face for {family}')
(OUT / 'fonts.css').write_text('\n'.join(css_out) + '\n', encoding='utf-8')
print('wrote', OUT / 'fonts.css')
